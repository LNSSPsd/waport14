"""Classify imports the target lacks, and generate logging traps for the callable ones.

kinds:
  func     - code: trap (log symbol name + backtrace to waport.log, abort)
  async    - Swift async function pointer: {rel32 -> trap, context size}
  enumcase - Swift resilient enum case tag (u32): 0, so the read succeeds and the
             trap of the API it belongs to reports instead of a null-deref
  data     - everything else (metadata, descriptors, ObjC classes, constants): weak null,
             which the ObjC and Swift runtimes treat as "weak-linked and absent"
"""
import os
import subprocess

THEOS = os.environ.get('THEOS', os.path.expanduser('~/theos'))
DEMANGLE = os.environ.get('SWIFT_DEMANGLE', os.path.join(THEOS, 'toolchain/swift-5.8/linux/host/bin/swift-demangle'))

SWIFT_DATA = (
    'nominal type descriptor', 'protocol conformance descriptor', 'type metadata for',
    'full type metadata', 'class metadata base offset', 'property descriptor',
    'method descriptor', 'protocol descriptor', 'protocol requirements base descriptor',
    'associated type descriptor', 'associated conformance descriptor',
    'base conformance descriptor', 'default associated conformance', 'type metadata pattern',
    'reflection metadata', 'opaque type descriptor', 'extension descriptor',
    'module descriptor', 'anonymous descriptor', 'value witness table',
    'protocol witness table for', 'lazy protocol witness table', 'type metadata lazy cache',
    'direct field offset', 'field offset', 'ObjC metaclass', 'metaclass for',
)


def demangle(names):
    if not names:
        return {}
    r = subprocess.run([DEMANGLE, '--simplified'], input='\n'.join(n[1:] for n in names),
                       capture_output=True, text=True, check=True)
    return dict(zip(names, r.stdout.split('\n')))


def classify(names, called):
    """{name: (kind, demangled)}. called: names some image calls through __stubs, i.e.
    functions (decides C/ObjC names; Swift names are decided by their demangling)."""
    sw = [n for n in names if n.startswith(('_$s', '_$S'))]
    dm = demangle(sw)
    out = {}
    for n in names:
        if n in dm:
            d = dm[n]
            if d.startswith('async function pointer to'):
                k = 'async'
            elif d.startswith('enum case for'):
                k = 'enumcase'
            elif d.startswith(SWIFT_DATA) and n not in called:
                k = 'data'
            else:
                k = 'func'
            out[n] = (k, d)
        else:
            out[n] = ('func' if n in called else 'data', n[1:])
    return out


def gen_asm(kinds):
    """traps.S for {name: kind} (func/async/enumcase)."""
    text, const, strs = [], [], []
    for i, (n, k) in enumerate(sorted(kinds.items())):
        q = f'"{n}"'
        strs.append(f'Lname{i}:\t.asciz "{n[1:]}"')
        trap = [f'\tadrp x0, Lname{i}@PAGE', f'\tadd x0, x0, Lname{i}@PAGEOFF', '\tb _waport_trap']
        if k == 'func':
            text += ['\t.p2align 2', f'\t.globl {q}', f'{q}:'] + trap
        elif k == 'async':
            # AsyncFunctionPointer {int32 function (relative), uint32 initial context size}
            text += ['\t.p2align 2', f'\t.globl {q}', f'{q}:', f'\t.long Ltrap{i} - {q}', '\t.long 64',
                     f'Ltrap{i}:'] + trap
        elif k == 'enumcase':
            const += ['\t.p2align 2', f'\t.globl {q}', f'{q}:', '\t.long 0']
    return '\n'.join(['// generated by tools/traps.py', '\t.text'] + text
                     + ['\t.section __TEXT,__const'] + const
                     + ['\t.section __TEXT,__cstring,cstring_literals'] + strs) + '\n'
