#!/bin/sh
# Build libwaport.dylib (arm64, iOS 14.0) with the theos toolchain.
#   usage: src/build-shim.sh <outdir> [traps.S] [extra sources...]
#   env:   THEOS (default ~/theos), SDK, WAPORT_LOG=1 for full diagnostics in waport.log
#   shim.S        - runtime entry points from newer iOS (objc_retain_xN, ...)
#   cfuncs.m      - newer C functions with a 14 equivalent
#   consts.m      - newer data constants (strings, structs)
#   compat.m      - add-if-missing fallbacks for newer ObjC methods
#   swiftnative.m - SwiftNativeNSObject (non-ARC)
#   overlays.swift - newer Swift overlay APIs (swift-5.8 toolchain, iOS 15.6 SDK interfaces,
#                   back-deployed Concurrency); overlays.aliases: their extra symbol names
#   mangle.m      - Concurrency substitutions (ScP, ScT, ...) in runtime type names
#   tweaks.m      - class-list functions rebound in injected tweaks (FLEX)
#   log.m, compat_cxx.mm - waport.log, trap target, diagnostics
#   traps.S       - generated by patch.py: one logging trap per missing function
set -e
OUT="$(mkdir -p "${1:?usage: build-shim.sh <outdir> [traps.S] [extra...]}" && cd "$1" && pwd)"
shift
TRAPS="${1:-}"
[ $# -gt 0 ] && shift
THEOS="${THEOS:-$HOME/theos}"
T="$THEOS/toolchain/linux/iphone/bin"
SDK="${SDK:-$THEOS/sdks/iPhoneOS14.5.sdk}"
HERE="$(cd "$(dirname "$0")" && pwd)"
CC="$T/clang -target arm64-apple-ios14.0 -isysroot $SDK -O2 -DWAPORT_LOG=${WAPORT_LOG:-0} -DWAPORT_BUILD=\"$(date -u +%Y%m%d-%H%M%S)\" -I$HERE"
O="$OUT/obj"
mkdir -p "$O"
$CC -fno-objc-arc -Wno-objc-missing-super-calls -c "$HERE/swiftnative.m" -o "$O/swiftnative.o"
# Swift: theos' swift-5.8 Linux toolchain wants libncurses.so.6 (only libncursesw.so.6 on some hosts)
ST="$THEOS/toolchain/swift-5.8/linux"
SWIFT_SDK="${SWIFT_SDK:-$THEOS/sdks/iPhoneOS15.6.sdk}"
mkdir -p "$O/hostlib"
[ -e /usr/lib/libncursesw.so.6 ] && ln -sf /usr/lib/libncursesw.so.6 "$O/hostlib/libncurses.so.6"
LD_LIBRARY_PATH="$O/hostlib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" "$ST/iphone/bin/swiftc" -resource-dir "$ST/iphone/lib/swift" \
    -target arm64-apple-ios14.0 -sdk "$SWIFT_SDK" -parse-as-library -enable-library-evolution -module-name WaportSwift \
    -O -c "$HERE/overlays.swift" -o "$O/overlays.o" 2>&1 | grep -v 'remark: unable to perform implicit import' || true
[ -s "$O/overlays.o" ]
set -- "$HERE/shim.S" "$HERE/cfuncs.m" "$HERE/consts.m" "$HERE/compat.m" "$HERE/mangle.m" "$HERE/tweaks.m" "$HERE/log.m" \
    "$HERE/compat_cxx.mm" ${TRAPS:+"$TRAPS"} "$@"
grep -v '^#' "$HERE/overlays.aliases" | grep . > "$O/aliases.txt"
$CC -fobjc-arc -dynamiclib -install_name @rpath/libwaport.dylib -Wl,-alias_list,"$O/aliases.txt" \
    -o "$OUT/libwaport.dylib" "$O/swiftnative.o" "$O/overlays.o" "$@" \
    -L"$ST/iphone/lib/swift-5.5/iphoneos" -L$SDK/usr/lib/swift -L"$ST/iphone/lib/swift/iphoneos" -lswiftCore -lswiftDispatch -lswiftUIKit -lobjc -lsqlite3 -lc++ -framework Foundation -framework UIKit -framework AVFoundation \
    -framework CoreVideo -framework CoreMedia -framework CoreGraphics -framework Security
echo "built $OUT/libwaport.dylib (WAPORT_LOG=${WAPORT_LOG:-0}${TRAPS:+, traps})"
